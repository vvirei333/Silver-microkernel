//! SHA-256 (FIPS 180-4) for bundle integrity checks.
//!
//! The kernel hashes the exact ELF bytes it is about to load, so a mismatched
//! or corrupted file is rejected before it becomes a runnable address space.
//! This is integrity, not authenticity: a real signature layer is the next
//! step once a trusted key is provisioned.

