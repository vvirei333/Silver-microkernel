out=[]
out.append("// Generated 5x7 uppercase pixel font for the browser (see tools/gen_font.py).")
out.append("// Each glyph is five column bytes; bit 0 is the top row.")
out.append("pub const GLYPH_WIDTH: u32 = 5;")
out.append("pub const GLYPH_HEIGHT: u32 = 7;")
out.append("")
out.append("const UNKNOWN: [u8; 5] = [0x7F, 0x41, 0x41, 0x41, 0x7F];")
out.append("")
out.append("pub fn glyph(character: char) -> &'static [u8; 5] {")
out.append("    let character = character.to_ascii_uppercase();")
out.append("    match character {")
for ch in sorted(glyphs):
    rows=glyphs[ch]
    cols=[0]*5
    for y,row in enumerate(rows):
        for x,cell in enumerate(row):
            if cell=='#':
                cols[x] |= 1<<y
    name = "'\\''" if ch=="'" else ("'\\\\'" if ch=="\\" else "'"+ch+"'")
    out.append("        %s => &[%s]," % (name, ", ".join("0x%02X"%c for c in cols)))
out.append("        _ => &UNKNOWN,")
out.append("    }")
out.append("}")
open('userspace/src/font5x7.rs','w').write("\n".join(out)+"\n")
